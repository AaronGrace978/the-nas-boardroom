"""Small phrase helpers shared by the seats and the Chair."""

from __future__ import annotations


def join_and(items: list[str] | tuple[str, ...]) -> str:
    items = list(items)
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    if len(items) == 2:
        return f"{items[0]} and {items[1]}"
    return ", ".join(items[:-1]) + f", and {items[-1]}"
